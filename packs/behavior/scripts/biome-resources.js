export function canonicalBiome(id){return BIOME_ALIASES[id]||id;}
export function biomeResource(id){return BIOME_RESOURCES[canonicalBiome(id)]?.[0]??null;}
export function eligibleBiome(id){return !!biomeResource(id);}
export function productionAllocations(v){
 if(v.dimension!=='minecraft:overworld')return [];
 const native=canonicalBiome(v.nativeBiome??v.biome),first=biomeResource(native);
 const result=first?[{slot:1,biome:native,...first}]:[];
 if(!v.biomeUnlocked)return result;
 const secondary=v.productionMode==='specialize'?native:v.productionMode==='unassigned'?null:canonicalBiome(v.secondary);
 const resource=biomeResource(secondary);
 if(resource)result.push({slot:2,biome:secondary,...resource});
 return result;
}
export function riverCropBonus(v){return productionAllocations(v).some(a=>a.biome==='minecraft:river')?0.10:0;}
export function migrateProduction(s){
 if(s.productionVersion>2)throw Error('Production save is newer than this addon');
 for(const v of Object.values(s.villages)){
  if(v.nativeBiome===undefined){
   v.nativeBiome=canonicalBiome(v.biome);v.biome=v.nativeBiome;
   if(v.secondary)v.secondary=canonicalBiome(v.secondary);
   v.productionMode??=v.biomeUnlocked&&eligibleBiome(v.secondary)?(v.secondary===v.nativeBiome?'specialize':'diversify'):'unassigned';
   v.available=[...new Set((v.available||[]).map(canonicalBiome))].filter(eligibleBiome);
   v.biomeSamples=Object.fromEntries(Object.entries(v.biomeSamples||{}).map(([id,sample])=>[canonicalBiome(id),sample]));
  }
  v.productionMode??=v.biomeUnlocked&&eligibleBiome(v.secondary)?(v.secondary===v.nativeBiome?'specialize':'diversify'):'unassigned';
 }
 s.productionVersion=2;
 return s;
}
